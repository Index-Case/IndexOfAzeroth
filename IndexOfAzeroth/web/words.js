function fillWords(text, fill) {
  if (text === null || text === undefined) return null;
  let missing = false;
  const out = text.replace(/\{([A-Za-z0-9]+)\}/g, (_, k) => {
    const v = fill?.[k];
    if (v === null || v === undefined || v === "") { missing = true; return ""; }
    return String(v);
  });
  return missing ? null : out;
}
const word = (key, fill) => fillWords(Words[key], fill);
const wordCount = (key, n, fill) => word(n === 1 && Object.hasOwn(Words, `${key}.one`) ? `${key}.one` : key, { n, ...fill });
const wordsOf = (prefix) => Object.fromEntries(Object.entries(Words).filter(([k]) => k.startsWith(`${prefix}.`))
  .map(([k, v]) => [k.slice(prefix.length + 1), v]));

