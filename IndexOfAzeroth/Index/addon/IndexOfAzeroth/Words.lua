function ns.Fill(text, fill)
  if text == nil then return nil end
  local missing = false
  local out = text:gsub("{(%w+)}", function(k)
    local v = fill and fill[k]
    if v ~= nil and v ~= "" then return tostring(v) end
    missing = true
    return ""
  end)
  if missing then return nil end
  return out
end
function ns.Word(key, fill) return ns.Fill(WORDS[key], fill) end
function ns.Count(key, n, fill)
  local f = { n = n }
  for k, v in pairs(fill or {}) do f[k] = v end
  return ns.Word(n == 1 and WORDS[key .. ".one"] and key .. ".one" or key, f)
end
function ns.WordsOf(prefix)
  local out, lead = {}, prefix .. "."
  for k, v in pairs(WORDS) do
    if k:sub(1, #lead) == lead then out[k:sub(#lead + 1)] = v end
  end
  return out
end
