TRAINERS_FILE, VENDORS_FILE = "ClassTrainers.lua", "Vendors.lua"
SIDES = {"Alliance": 1, "Horde": 2}
FAR_WALK = 1e9
LUA_KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil",
                "not", "or", "repeat", "return", "then", "true", "until", "while"}


def lua(v):
    if isinstance(v, dict):
        out = []
        for k, x in v.items():
            bare = isinstance(k, str) and re.match(r"^[A-Za-z_]\w*$", k) and k not in LUA_KEYWORDS
            out.append(f"{k if bare else '[' + (json.dumps(k, ensure_ascii=False) if isinstance(k, str) else str(k)) + ']'}={lua(x)}")
        return "{" + ",".join(out) + "}"
    if isinstance(v, (list, tuple)):
        return "{" + ",".join(lua(x) for x in v) + "}"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, float):
        r = round(v, 1)
        return str(int(r)) if r == int(r) else repr(r)
    return str(v)


def bits(mask):
    return [k for k in range(mask.bit_length()) if mask >> k & 1]


def side_mask(sv):
    from layers import attacks
    import facts
    return sum(b for side, b in SIDES.items() if not attacks(sv, facts.faction_bit(side)))


def spots(sv, geo):
    area_map = getattr(geo, "area_map", None) or {}
    out = []
    for area, pts in sv["s"].items():
        for x, y in pts:
            w = geo.area_to_world(area, x, y)
            if w:
                out.append([w[2], w[0], w[1], int(area_map.get(str(area)) or 0)])
    return out


def npc_row(sv, geo, walkers, cats):
    row = {"id": sv.get("id") or 0, "n": sv["n"], "f": side_mask(sv),
           "k": [[c, d] if d is not None else [c] for c, d in sv["cats"] if c in cats], "s": spots(sv, geo)}
    if sv.get("z") is not None:
        row["z"] = sv["z"]
    walk = walkers.get(sv.get("id"))
    if walk is not None:
        row["w"] = FAR_WALK if math.isinf(walk) else walk
    if sv.get("prices"):
        row["p"] = sv["prices"]
    return row


def trainer_table(classspells, services, geo, walkers, race_rows=None, trainer_costs=None):
    classes = {}
    for cid, c in (classspells.get("classes") or {}).items():
        levels = {}
        for lv, v in sorted(c["levels"].items(), key=lambda kv: int(kv[0])):
            row = []
            for s in v["spells"]:
                e = {"id": s["id"], "n": s["name"], "r": s.get("rank") or ""}
                if s.get("cost") is not None:
                    e["c"] = s["cost"]
                if s.get("prev"):
                    e["p"] = s["prev"]
                if s.get("races"):
                    e["ra"] = bits(s["races"])
                if s.get("needs"):
                    e["ne"] = list(s["needs"])
                if s.get("trainer") is False:
                    e["x"] = True
                if s.get("dmg"):
                    e["d"] = True
                row.append(e)
            levels[int(lv)] = row
        theirs = (trainer_costs or {}).get(str(cid)) or {}
        cost = {int(lv): theirs.get(lv) or v.get("cost") for lv, v in c["levels"].items() if theirs.get(lv) or v.get("cost")}
        classes[int(cid)] = {"levels": levels, **({"cost": cost} if cost else {})}
    races = {}
    for r in race_rows or ():
        if r.get("file"):
            races.setdefault(r["file"], {})[r.get("side") or "any"] = r["bit"].bit_length() - 1
    trainers = [npc_row(sv, geo, walkers, {"class"}) for sv in services if any(c == "class" for c, _ in sv["cats"])]
    return {"build": classspells.get("build") or "", "races": races, "classes": classes,
            "trainers": [t for t in trainers if t["s"]],
            "teaches": {int(n): sorted(ids) for n, ids in (classspells.get("trainers") or {}).items()}}


def vendor_table(services, geo, walkers):
    rows = [npc_row(sv, geo, walkers, errands.MERCHANT) for sv in services if any(c in errands.MERCHANT for c, _ in sv["cats"])]
    return [r for r in rows if r["s"]]


def restock_items(vendors, item_name):
    ids = sorted({r[2] for v in vendors for kind in ("water", "ammo") for r in (v.get("p") or {}).get(kind) or ()})
    names = {i: item_name(i) for i in ids}
    return {i: n for i, n in names.items() if n}


def vendor_reagents(services, item_name):
    out = set()
    for sv in services:
        said = set(sv.get("sells") or ())
        if said:
            out |= {int(i) for i in sv.get("goods") or () if item_name(int(i)) in said}
    return {i: True for i in sorted(out)}


def source(name, table, notes, more=()):
    return (f"-- Generated by tools/build_addon_chores.py. Don't edit, rebuild.\n"
            f"-- Sources: {notes}\n"
            "local _, ns = ...\n"
            f"ns.{name} = {lua(table)}\n" + "".join(f"ns.{n} = {lua(t)}\n" for n, t in more))


def write_in_place(path, text):
    data = text.encode("utf-8")
    with open(path, "r+b" if os.path.exists(path) else "wb") as f:
        f.seek(0)
        f.write(data)
        f.truncate()


def write(addon, classspells, services, geo, walkers, race_rows=None, trainer_costs=None, notes="classspells.json and world.json",
          item_name=None):
    named = item_name or (lambda i: None)
    trainers = trainer_table(classspells, services, geo, walkers, race_rows, trainer_costs)
    vendors = vendor_table(services, geo, walkers)
    items = restock_items(vendors, named)
    write_in_place(os.path.join(addon, TRAINERS_FILE), source("ClassTrainers", trainers, notes))
    write_in_place(os.path.join(addon, VENDORS_FILE), source("Vendors", vendors, notes, [
        ("RestockItems", items), ("VendorReagents", vendor_reagents(services, named))]))
    return trainers, vendors


def addon_folder(asked=None):
    return asked or game.addon_to_write()


def write_from_data(addon=None):
    addon = addon_folder(addon)
    if not addon:
        print("ClassTrainers.lua, Vendors.lua: not written, a worktree with no WCC_ADDON copy")
        return None
    from layers import WorldLayers
    world = WorldLayers()
    classspells = dropguard.made(os.path.join(ROOT, "data", "classspells.json"))
    try:
        import races
        race_rows = races.playable()
    except (OSError, ValueError, KeyError, game.GameNotFound) as e:
        print(f"the client's race table not read: {e}")
        race_rows = None
    from gamedata import item_name
    trainers, vendors = write(addon, classspells, world.services, world.geo, world.walking(), race_rows, world.trainer_costs,
                              item_name=item_name)
    spells = sum(len(v) for c in trainers["classes"].values() for v in c["levels"].values())
    print(f"{TRAINERS_FILE}: {len(trainers['classes'])} classes, {spells} spells, {len(trainers['trainers'])} trainers, "
          f"{len(trainers['races'])} races. {VENDORS_FILE}: {len(vendors)} vendors")
    return trainers, vendors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--addon", default=None, help="the addon folder to write into (a working copy of the addon)")
    write_from_data(ap.parse_args().addon)


if __name__ == "__main__":
    import builder
    builder.run(main)
